from __future__ import annotations
"""
whatsapp.py – Automated WhatsApp Multi-Bet Notification System.

Supports:
  1. CallMeBot (Free, zero-config personal WhatsApp API – standard for personal bots)
     - Setup: message the number listed at callmebot.com/blog/free-api-whatsapp-messages
       with "I allow callmebot to send me messages" to receive your personal apikey.
       The gateway number rotates, so never hardcode it.
  2. Twilio WhatsApp API (Enterprise WhatsApp messaging)
"""
import os
import urllib.parse
import logging
import requests
from typing import Any, Dict, Optional

logger = logging.getLogger(__name__)

# Config from environment or user settings
WHATSAPP_PHONE = os.getenv("WHATSAPP_PHONE", "")
WHATSAPP_APIKEY = os.getenv("WHATSAPP_APIKEY", "")
WHATSAPP_PROVIDER = os.getenv("WHATSAPP_PROVIDER", "callmebot")  # "callmebot" or "twilio"


def format_combo_whatsapp_message(
    combo: Dict[str, Any],
    matchday_label: str = "Today",
    currency: str = "UGX",
) -> str:
    """Format a clean, readable WhatsApp alert message for a multi-bet slip."""
    from app.core.currency import format_stake_dual

    legs_count = combo.get("legs_count", len(combo.get("legs", [])))
    tot_odds = combo.get("total_odds", 2.00)
    avg_p = combo.get("avg_leg_probability", combo.get("combined_probability", 0.85)) * 100
    comb_p = combo.get("combined_probability", 0.60) * 100
    ev_val = combo.get("expected_value_percent", 0.0)
    stake_str = format_stake_dual(combo.get("kelly_stake_amount", 50.0), currency)
    stake_pct = combo.get("kelly_stake_percent", 5.0)

    lines = [
        f"🏆 *FIE BANKER MULTI-BET ({legs_count} TEAMS)*",
        f"📅 Matchday: *{matchday_label}*",
        f"💰 Combined Odds: *{tot_odds:.2f}*",
        f"⭐ Avg Team Confidence: *{avg_p:.1f}% (Bankers)*",
        f"🎯 Slip Win Probability: *{comb_p:.1f}%* | EV: *{ev_val:+.1f}%*",
        f"💵 Quarter Kelly Stake: *{stake_str} ({stake_pct}%)*",
        "",
        "📋 *SLIP SELECTIONS (All Ugandan Time EAT):*",
    ]

    for idx, leg in enumerate(combo.get("legs", []), 1):
        m_name = leg.get("match", "Match")
        sel = leg.get("selection", "Selection")
        m_odds = leg.get("odds", 1.20)
        p_val = leg.get("probability", 0.85) * 100
        ko_eat = leg.get("kickoff_eat", "")
        comp = leg.get("competition", "")
        ai_squad = leg.get("ai_squad", {})
        injury_txt = ai_squad.get("injuries", "")

        est_tag = "" if leg.get("odds_source", "market") == "market" else " (est.)"
        lines.append(f"*{idx}. {m_name}* ({comp})")
        lines.append(f"   👉 *{sel}* @ {m_odds:.2f}{est_tag} (Prob: {p_val:.1f}%)")
        lines.append(f"   ⏰ Kickoff: {ko_eat}")
        if injury_txt:
            lines.append(f"   🏥 Squad/Injury Check: {injury_txt[:80]}")
        lines.append("")

    lines.append("⚡ _Generated by Football Intelligence Engine (24/7 Sentinel)_")
    return "\n".join(lines)


def send_whatsapp_message(
    text: str,
    phone: Optional[str] = None,
    apikey: Optional[str] = None,
    provider: str = "callmebot",
) -> Dict[str, Any]:
    """Send text message to WhatsApp using configured provider (CallMeBot or Twilio)."""
    p_phone = (phone or WHATSAPP_PHONE or os.getenv("WHATSAPP_PHONE", "")).strip()
    p_key = (apikey or WHATSAPP_APIKEY or os.getenv("WHATSAPP_APIKEY", "")).strip()

    # Clean phone: remove spaces, dashes, parentheses
    p_clean = p_phone.replace(" ", "").replace("-", "").replace("(", "").replace(")", "")
    if p_clean.startswith("+"):
        p_clean = p_clean[1:]

    if not p_clean:
        return {"success": False, "error": "No WhatsApp phone number provided."}

    if provider.lower() == "callmebot":
        if not p_key:
            return {
                "success": False,
                "error": "CallMeBot API key required. Message the number listed on callmebot.com/blog/free-api-whatsapp-messages from your phone and send 'I allow callmebot to send me messages' (or 'Recover APIKey' if already activated)."
            }
        encoded_text = urllib.parse.quote(text)
        url = f"https://api.callmebot.com/whatsapp.php?phone={p_clean}&text={encoded_text}&apikey={p_key}"
        try:
            resp = requests.get(url, timeout=15)
            if resp.status_code == 200 and ("Message sent" in resp.text or "ok" in resp.text.lower() or "queued" in resp.text.lower()):
                logger.info(f"[WhatsApp] Alert dispatched successfully to {p_clean}")
                return {"success": True, "provider": "callmebot", "message": "WhatsApp alert dispatched successfully!"}
            elif resp.status_code == 200:
                # CallMeBot sometimes returns text like "Message queued" or plain 200
                return {"success": True, "provider": "callmebot", "message": resp.text.strip()}
            else:
                return {"success": False, "error": f"CallMeBot HTTP {resp.status_code}: {resp.text}"}
        except Exception as e:
            logger.error(f"[WhatsApp] Send error: {e}")
            return {"success": False, "error": str(e)}

    elif provider.lower() == "twilio":
        sid = os.getenv("TWILIO_ACCOUNT_SID", "")
        token = os.getenv("TWILIO_AUTH_TOKEN", "")
        from_num = os.getenv("TWILIO_WHATSAPP_FROM", "whatsapp:+14155238886")
        if not (sid and token):
            return {"success": False, "error": "TWILIO_ACCOUNT_SID and TWILIO_AUTH_TOKEN must be configured."}
        try:
            to_num = f"whatsapp:+{p_clean}"
            resp = requests.post(
                f"https://api.twilio.com/2010-04-01/Accounts/{sid}/Messages.json",
                auth=(sid, token),
                data={"From": from_num, "To": to_num, "Body": text},
                timeout=15,
            )
            if resp.status_code in (200, 201):
                return {"success": True, "provider": "twilio", "sid": resp.json().get("sid")}
            else:
                return {"success": False, "error": f"Twilio HTTP {resp.status_code}: {resp.text}"}
        except Exception as e:
            return {"success": False, "error": str(e)}

    return {"success": False, "error": f"Unknown provider: {provider}"}


def send_combo_whatsapp_alert(
    combo: Dict[str, Any],
    matchday_label: str = "Today",
    phone: Optional[str] = None,
    apikey: Optional[str] = None,
    currency: str = "UGX",
    provider: str = "callmebot",
) -> Dict[str, Any]:
    """Format and send a multi-bet slip alert to WhatsApp."""
    msg = format_combo_whatsapp_message(combo, matchday_label=matchday_label, currency=currency)
    return send_whatsapp_message(msg, phone=phone, apikey=apikey, provider=provider)
